#!/usr/bin/env node
/*
 * generate-icon-variants.js
 *
 * Generates App Store icon variants for Apple's Product Page Optimization
 * (PPO) test 2 — see marketing/07-FUNNEL-AND-ASO.md week 8–11.
 *
 * Control icon (the sound-wave-ripples + ELSEWARE wordmark) lives at
 * scripts/generate-icon.js / assets/icon.png. Don't touch that. We test
 * against it.
 *
 * Output: assets/icon-variants/{A-serif-e,B-place-mosaic}.svg at 1024×1024.
 *
 * Convert SVG → PNG before uploading to App Store Connect:
 *   brew install librsvg
 *   for f in assets/icon-variants/*.svg; do
 *     rsvg-convert -w 1024 -h 1024 "$f" -o "${f%.svg}.png"
 *   done
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT_DIR = path.join(ROOT, 'assets', 'icon-variants');

const SIZE = 1024;
const RADIUS = 224; // Apple's icon corner radius scaled to 1024 (matches stock).

const palette = {
  cream: '#f4f1ec',
  warm: '#faf8f4',
  ink: '#2e2a24',
  inkDim: '#7a7268',
  inkMute: '#a89e94',
  accent: '#a688b5',
  accentSoft: '#f3eef6',
  accentLight: '#e8ddef',
  border: '#e0dbd4',
  cardBorder: '#e8e4de',
  night: '#1a1714',
  nightInk: '#e7e3da',
};

const serif = "'Georgia', 'Times New Roman', serif";
const grot = "'Helvetica Neue', 'Inter', 'Arial', sans-serif";

// ---------- Variant A — Soft Serif "E" ----------
//
// Hypothesis: a single serif glyph on cream is more memorable on a crowded
// home screen than the sound-wave control. Tests "aesthetic identity" >
// "literal product depiction" hypothesis.

function variantA() {
  return `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" width="${SIZE}" height="${SIZE}" viewBox="0 0 ${SIZE} ${SIZE}">
<!-- Variant A — Soft Serif E (PPO test 2). Generated by scripts/generate-icon-variants.js. -->

  <!-- Subtle radial warmth so the cream doesn't read flat at thumb-size. -->
  <defs>
    <radialGradient id="warmth" cx="50%" cy="38%" r="62%">
      <stop offset="0%" stop-color="#faf8f4" stop-opacity="1"/>
      <stop offset="100%" stop-color="${palette.cream}" stop-opacity="1"/>
    </radialGradient>
  </defs>

  <rect width="${SIZE}" height="${SIZE}" rx="${RADIUS}" fill="url(#warmth)"/>

  <!-- Soft inner frame — same gesture as the wallpapers, signals "intentional." -->
  <rect x="80" y="80" width="${SIZE - 160}" height="${SIZE - 160}" rx="${RADIUS - 80}" fill="none" stroke="#d8d2c8" stroke-width="2" opacity="0.5"/>

  <!-- The glyph. Italic serif, slightly oversized, optical-centered up. -->
  <text x="${SIZE / 2}" y="${SIZE / 2 + 240}" font-family="${serif}" font-style="italic" font-weight="300" font-size="780" fill="${palette.ink}" text-anchor="middle">e</text>

  <!-- Sub-mark: a single rule under the glyph, matches wallpaper system. -->
  <line x1="${SIZE / 2 - 60}" y1="${SIZE - 200}" x2="${SIZE / 2 + 60}" y2="${SIZE - 200}" stroke="${palette.accent}" stroke-width="3" opacity="0.7"/>

  <!-- Tiny brand mark -->
  <text x="${SIZE / 2}" y="${SIZE - 130}" font-family="${grot}" font-size="36" letter-spacing="10" fill="${palette.inkDim}" text-anchor="middle" font-weight="600">ELSEWARE</text>
</svg>
`;
}

// ---------- Variant B — Six-Place Mosaic ----------
//
// Hypothesis: a 2x3 mosaic that telegraphs "this app has 6 different places"
// pre-answers the buyer's first question (what is this?) faster than a
// glyph. Tests "literal product depiction" > "aesthetic identity" hypothesis.

function variantB() {
  // 2×3 grid. Inset to leave Apple's safe corners breathing.
  const inset = 140;
  const gridW = SIZE - inset * 2;
  const gridH = SIZE - inset * 2;
  const cols = 2;
  const rows = 3;
  const gap = 20;
  const cellW = (gridW - gap * (cols - 1)) / cols;
  const cellH = (gridH - gap * (rows - 1)) / rows;

  // Place-specific accents echo the wallpaper palette (day/night signals).
  const places = [
    { name: 'Tokyo',     accent: 'rain',    mode: 'day'   },
    { name: 'Lisbon',    accent: 'storm',   mode: 'night' },
    { name: 'Seoul',     accent: 'grid',    mode: 'day'   },
    { name: 'Siberia',   accent: 'rails',   mode: 'night' },
    { name: 'Bali',      accent: 'sun',     mode: 'day'   },
    { name: 'Tulum',     accent: 'horizon', mode: 'day'   },
  ];

  const cells = places.map((p, i) => {
    const col = i % cols;
    const row = Math.floor(i / cols);
    const x = inset + col * (cellW + gap);
    const y = inset + row * (cellH + gap);
    const bg = p.mode === 'night' ? palette.night : palette.cream;
    const ink = p.mode === 'night' ? palette.nightInk : palette.ink;
    const dim = p.mode === 'night' ? palette.inkMute : palette.inkDim;

    let accentSvg = '';
    const cx = x + cellW / 2;
    const cy = y + cellH / 2 - 30;
    switch (p.accent) {
      case 'rain':
        accentSvg = Array.from({ length: 5 }, (_, j) => {
          const lx = x + 50 + j * 30;
          return `<line x1="${lx}" y1="${y + 40}" x2="${lx - 8}" y2="${y + 80}" stroke="${dim}" stroke-width="2" opacity="0.5"/>`;
        }).join('\n      ');
        break;
      case 'storm':
        accentSvg = `<polyline points="${x + 60},${y + 40} ${x + 100},${y + 80} ${x + 80},${y + 80} ${x + 110},${y + 120}" fill="none" stroke="${palette.accent}" stroke-width="3" opacity="0.55"/>`;
        break;
      case 'grid':
        accentSvg = `
        <line x1="${x + 50}" y1="${y + 40}" x2="${x + 50}" y2="${y + 100}" stroke="${dim}" stroke-width="1.5" opacity="0.5"/>
        <line x1="${x + 90}" y1="${y + 40}" x2="${x + 90}" y2="${y + 100}" stroke="${dim}" stroke-width="1.5" opacity="0.5"/>
        <line x1="${x + 130}" y1="${y + 40}" x2="${x + 130}" y2="${y + 100}" stroke="${dim}" stroke-width="1.5" opacity="0.5"/>
        <line x1="${x + 50}" y1="${y + 70}" x2="${x + 130}" y2="${y + 70}" stroke="${dim}" stroke-width="1.5" opacity="0.5"/>`;
        break;
      case 'rails':
        accentSvg = `
        <line x1="${x + 50}" y1="${y + 70}" x2="${x + cellW - 50}" y2="${y + 70}" stroke="${dim}" stroke-width="2" opacity="0.5"/>
        <line x1="${x + 50}" y1="${y + 90}" x2="${x + cellW - 50}" y2="${y + 90}" stroke="${dim}" stroke-width="2" opacity="0.5"/>`;
        break;
      case 'sun':
        accentSvg = `
        <circle cx="${x + cellW / 2}" cy="${y + 75}" r="40" fill="none" stroke="${palette.accent}" stroke-width="2.5" opacity="0.55"/>`;
        break;
      case 'horizon':
        accentSvg = `
        <line x1="${x + 50}" y1="${y + 80}" x2="${x + cellW - 50}" y2="${y + 80}" stroke="${palette.accent}" stroke-width="3" opacity="0.55"/>
        <line x1="${x + 80}" y1="${y + 100}" x2="${x + cellW - 80}" y2="${y + 100}" stroke="${dim}" stroke-width="1.5" opacity="0.4"/>`;
        break;
    }

    return `
    <g>
      <rect x="${x}" y="${y}" width="${cellW}" height="${cellH}" rx="38" fill="${bg}" stroke="${palette.cardBorder}" stroke-width="2"/>
      ${accentSvg}
      <text x="${x + cellW / 2}" y="${y + cellH - 50}" font-family="${serif}" font-style="italic" font-weight="300" font-size="58" fill="${ink}" text-anchor="middle">${p.name}</text>
    </g>`;
  }).join('\n');

  return `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" width="${SIZE}" height="${SIZE}" viewBox="0 0 ${SIZE} ${SIZE}">
<!-- Variant B — Six-Place Mosaic (PPO test 2). Generated by scripts/generate-icon-variants.js. -->
  <rect width="${SIZE}" height="${SIZE}" rx="${RADIUS}" fill="${palette.cream}"/>

  ${cells}
</svg>
`;
}

// ---------- main ----------

const variants = [
  { id: 'A-serif-e',       svg: variantA },
  { id: 'B-place-mosaic',  svg: variantB },
];

function main() {
  if (!fs.existsSync(OUT_DIR)) fs.mkdirSync(OUT_DIR, { recursive: true });
  for (const f of fs.readdirSync(OUT_DIR).filter((n) => n.endsWith('.svg'))) {
    fs.unlinkSync(path.join(OUT_DIR, f));
  }
  for (const v of variants) {
    const filename = path.join(OUT_DIR, `${v.id}.svg`);
    fs.writeFileSync(filename, v.svg(), 'utf8');
    console.log(`✓ ${path.relative(ROOT, filename)}`);
  }
  console.log(`\nWrote ${variants.length} icon variants to ${path.relative(ROOT, OUT_DIR)}/`);
}

main();
